#example 1 : range(stop))
for i in range(10):
    print(i)

#example 2 : range(start, stop)
for i in range(2, 10):
    print(i)

#example 3 : range(start, stop, step)
for i in range(2, 10, 2):
    print(i)

#even number
for i in range(2, 101, 2):
    print(i)

#odd numbers
for i in range(1, 101, 2):
    print(i)
  
